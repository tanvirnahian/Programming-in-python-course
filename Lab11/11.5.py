import numpy as np

arr1 = np.array([1, 2, 3, 4])
arr2 = np.array([5, 6, 7, 8])

print("Sum of arr1:", np.sum(arr1))
print("Product of arr1:", np.prod(arr1))
print("Difference of arr1:", np.diff(arr1))

print("Sum of arr2:", np.sum(arr2))
print("Product of arr2:", np.prod(arr2))
print("Difference of arr2:", np.diff(arr2))